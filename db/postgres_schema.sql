-- ============================================================
-- PT Merge Mining Industri — Procurement OLTP schema (PostgreSQL 14+)
--
-- Source of truth for the live app. ClickHouse keeps the same tables as the
-- analytics warehouse and is fed from here by db/ch_sync (see RUNBOOK).
--
-- Column names and meanings mirror db/clickhouse_schema.sql so API responses
-- and the warehouse sync stay 1:1. Differences from ClickHouse:
--   * no `version` columns — rows are updated in place
--   * real primary keys, foreign keys and unique constraints
--   * legacy_* ids (used in frontend URLs) come from identity sequences
--   * updated_at is maintained by trigger, so the sync can rely on it
--   * is_deleted stays a smallint 0/1 soft-delete flag, as in ClickHouse
--
-- Must run on PostgreSQL 14 (local dev) and 16 (mmi-postgres): no
-- NULLS NOT DISTINCT, no MERGE.
-- ============================================================

SET client_min_messages = warning;

-- ── Shared trigger: keep updated_at honest ───────────────────────────────────
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := clock_timestamp();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ── Document number counters (PR-YYYY-NNN, PO-YYYY-NNN, ITEM-NNNN, V-NNNN) ───
-- Incremented with INSERT … ON CONFLICT DO UPDATE … RETURNING inside the
-- creating transaction, so two concurrent requests can never get the same
-- number. year = 0 for counters that do not reset yearly (ITEM, V).
CREATE TABLE IF NOT EXISTS doc_counters (
    doc_type   text     NOT NULL,
    year       integer  NOT NULL DEFAULT 0,
    last_no    integer  NOT NULL DEFAULT 0,
    PRIMARY KEY (doc_type, year)
);

