-- ── updated_at triggers + sync indexes on every mutable table ────────────────
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'purposes', 'users', 'vendors', 'items', 'purchase_requests',
    'purchase_request_items', 'purchase_orders', 'purchase_order_items',
    'purchase_order_charges', 'item_requests', 'pr_templates', 'pr_template_items'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I_set_updated_at ON %I', t, t);
    EXECUTE format('CREATE TRIGGER %I_set_updated_at BEFORE UPDATE ON %I
                    FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t, t);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (updated_at)', t || '_updated_at_idx', t);
  END LOOP;
END $$;
